#!/usr/bin/env python3
"""Install ora-skills git hooks into a per-clone, UNTRACKED hooks directory.

    python tools/install_hooks.py [--repo PATH] [--check]

Why: `core.hooksPath` used to point at the main checkout's tracked `tools/hooks`. That
directory changes with whatever branch the main checkout has checked out, so while it sat on
a branch cut before `tools/hooks/pre-push` existed, git ran NO pre-push hook in any worktree
and the Invariant 3 confidentiality gate was silently off.

What this does (idempotent; never deletes anything):
  * resolves the clone's shared git dir (`git rev-parse --git-common-dir`, so every linked
    worktree shares one install) and writes `<common-dir>/ora-hooks/`:
      - one small shim per hook name (every file in this tree's `tools/hooks/` plus
        `pre-push`). Git runs the shim; the shim runs `tools/hooks/<name>` from the tree being
        committed or pushed (the worktree git invoked it in) when that file exists;
      - `prepush_confidential_scan.py`, a copy of this tree's scanner. When the tree has no
        tracked `tools/hooks/pre-push` (any branch cut before PR #231), the pre-push shim runs
        this copy instead. No copy, or no Python 3.8+, BLOCKS the push: pre-push never
        falls through to "allow";
      - other hooks with no tracked counterpart in the tree do nothing (exit 0), exactly
        what git does for a hook that does not exist;
  * sets `core.hooksPath` (local config) to that directory and reports the previous value;
  * refuses (exit 2) if any linked worktree overrides `core.hooksPath` through
    `extensions.worktreeConfig`, because that override would silently win.
A file already in `ora-hooks/` with different content is renamed to `<name>.bak-<UTC stamp>`
before the new one is written; identical files are left untouched (mtime included).

`--check` writes nothing: exit 0 when the install is present, current and active, 1 otherwise.
Re-run the installer after pulling a change to `tools/prepush_confidential_scan.py` or
`tools/hooks/` so the fallback scanner and the shim set stay current (`--check` says when).

Exit codes: 0 ok, 1 `--check` found drift, 2 error.
"""
import argparse
import datetime
import os
import stat
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SCAN_NAME = "prepush_confidential_scan.py"
SCAN_SRC = os.path.join(HERE, SCAN_NAME)
TRACKED_HOOKS_DIR = os.path.join(HERE, "hooks")
HOOKS_SUBDIR = "ora-hooks"
MARKER = "ORA-HOOKS-SHIM v1"

SHIM_HEAD = """#!/bin/sh
# {marker} ({name}) -- generated by tools/install_hooks.py into the clone's untracked
# <git-common-dir>/{subdir}; do not edit (re-run the installer instead).
# Runs the tracked tools/hooks/{name} from the tree git invoked this hook in, when it exists.
ROOT=$(git rev-parse --show-toplevel 2>/dev/null)
if [ -n "$ROOT" ] && [ -f "$ROOT/tools/hooks/{name}" ]; then
  exec sh "$ROOT/tools/hooks/{name}" "$@"
fi
"""

SHIM_TAIL_DEFAULT = """# No tracked tools/hooks/{name} in this tree: behave as if the hook did not exist.
exit 0
"""

# Fail-closed: every path that does not reach `exec <python> <scanner>` exits 1.
SHIM_TAIL_PREPUSH = """# No tracked pre-push in this tree (branch predates it): run the installer's fallback copy of
# the confidentiality scan. No copy or no usable Python 3.8+ => the push is BLOCKED.
# Emergency bypass (only after verifying the push is clean): git push --no-verify
HOOKS_DIR=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
SCAN="$HOOKS_DIR/{scan}"
if [ ! -f "$SCAN" ]; then
  echo "pre-push BLOCKED (fail-closed): this tree has no tools/hooks/pre-push and the fallback scanner $SCAN is missing; re-run tools/install_hooks.py from a current checkout." >&2
  exit 1
fi
PY=
for c in python python3 py; do
  if command -v "$c" >/dev/null 2>&1 &&
     "$c" -c "import sys; sys.exit(0 if sys.version_info >= (3, 8) else 1)" </dev/null >/dev/null 2>&1; then
    PY=$c
    break
  fi
done
if [ -z "$PY" ]; then
  echo "pre-push BLOCKED (fail-closed): no Python 3.8+ found to run the confidentiality scan." >&2
  exit 1
fi
exec "$PY" "$SCAN" "$@"
exit 1
"""


class InstallError(Exception):
    pass


def git(repo, *args, check=True):
    p = subprocess.run(["git", "-C", repo] + list(args), capture_output=True, text=True)
    if check and p.returncode != 0:
        raise InstallError("git %s failed: %s" % (" ".join(args), p.stderr.strip()))
    return p


def shim_text(name):
    tail = SHIM_TAIL_PREPUSH if name == "pre-push" else SHIM_TAIL_DEFAULT
    return (SHIM_HEAD + tail).format(marker=MARKER, name=name, subdir=HOOKS_SUBDIR, scan=SCAN_NAME)


def hook_names():
    names = {"pre-push"}
    if os.path.isdir(TRACKED_HOOKS_DIR):
        for n in os.listdir(TRACKED_HOOKS_DIR):
            p = os.path.join(TRACKED_HOOKS_DIR, n)
            if os.path.isfile(p) and "." not in n:
                names.add(n)
    return sorted(names)


def desired_files():
    """{filename: bytes} for everything the installer owns in ora-hooks/."""
    if not os.path.isfile(SCAN_SRC):
        raise InstallError("scanner not found beside the installer: %s" % SCAN_SRC)
    files = {n: shim_text(n).encode("utf-8") for n in hook_names()}
    with open(SCAN_SRC, "rb") as f:
        files[SCAN_NAME] = f.read()
    return files


def common_dir(repo):
    if not os.path.isdir(repo):
        raise InstallError("not a directory: %s" % repo)
    p = git(repo, "rev-parse", "--path-format=absolute", "--git-common-dir", check=False)
    if p.returncode != 0 or not p.stdout.strip():
        raise InstallError("not a git repository: %s" % repo)
    return os.path.normpath(p.stdout.strip())


def same_path(a, b):
    return os.path.normcase(os.path.normpath(a)) == os.path.normcase(os.path.normpath(b))


def read_bytes(path):
    try:
        with open(path, "rb") as f:
            return f.read()
    except OSError:
        return None


def is_executable(path):
    return os.name == "nt" or bool(os.stat(path).st_mode & stat.S_IXUSR)


def backup_name(path):
    stamp = datetime.datetime.now(datetime.timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    cand, i = "%s.bak-%s" % (path, stamp), 1
    while os.path.lexists(cand):
        cand, i = "%s.bak-%s-%d" % (path, stamp, i), i + 1
    return cand


def worktree_overrides(repo, hooks_dir):
    """Linked worktrees whose effective core.hooksPath is not hooks_dir (only possible when
    extensions.worktreeConfig lets a config.worktree override the shared value)."""
    flag = git(repo, "config", "--type=bool", "--get", "extensions.worktreeConfig", check=False)
    if flag.stdout.strip() != "true":
        return []
    bad = []
    for line in git(repo, "worktree", "list", "--porcelain").stdout.splitlines():
        if not line.startswith("worktree "):
            continue
        wt = line[len("worktree "):]
        if not os.path.isdir(wt):
            continue  # prunable / on another machine: git cannot run hooks there anyway
        val = git(wt, "config", "--get", "core.hooksPath", check=False).stdout.strip()
        if not val or not same_path(val, hooks_dir):
            bad.append((wt, val))
    return bad


def check(repo):
    hooks_dir = os.path.join(common_dir(repo), HOOKS_SUBDIR)
    problems = []
    for name, data in desired_files().items():
        path = os.path.join(hooks_dir, name)
        if read_bytes(path) != data:
            problems.append("missing or stale: %s" % path)
        elif name != SCAN_NAME and not is_executable(path):
            problems.append("not executable: %s" % path)
    cur = git(repo, "config", "--get", "core.hooksPath", check=False).stdout.strip()
    if not cur or not same_path(cur, hooks_dir):
        problems.append("core.hooksPath is %r, expected %s" % (cur or None, hooks_dir))
    problems += ["worktree %s overrides core.hooksPath (%r)" % b
                 for b in worktree_overrides(repo, hooks_dir)]
    return hooks_dir, problems


def install(repo, log):
    hooks_dir = os.path.join(common_dir(repo), HOOKS_SUBDIR)
    files = desired_files()
    os.makedirs(hooks_dir, exist_ok=True)
    changed = 0
    for name, data in files.items():
        path = os.path.join(hooks_dir, name)
        if os.path.lexists(path) and not os.path.isfile(path):
            raise InstallError("refusing to replace non-file %s (move it aside by hand)" % path)
        existing = read_bytes(path)
        if existing != data:
            if existing is not None:
                bak = backup_name(path)
                os.rename(path, bak)
                log("backed up %s -> %s" % (name, os.path.basename(bak)))
            tmp = path + ".tmp-install"
            with open(tmp, "wb") as f:
                f.write(data)
            os.replace(tmp, path)
            log("wrote %s" % path)
            changed += 1
        if name != SCAN_NAME and not is_executable(path):
            mode = os.stat(path).st_mode
            os.chmod(path, mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)
            changed += 1
    want = hooks_dir.replace("\\", "/")
    cur = git(repo, "config", "--get", "core.hooksPath", check=False).stdout.strip()
    if not cur or not same_path(cur, hooks_dir):
        git(repo, "config", "--local", "core.hooksPath", want)
        log("core.hooksPath: %s -> %s" % (cur or "(unset)", want))
        changed += 1
    eff = git(repo, "config", "--get", "core.hooksPath", check=False).stdout.strip()
    if not same_path(eff, hooks_dir):
        raise InstallError("core.hooksPath still resolves to %r after install (set in a higher-"
                           "precedence config such as GIT_CONFIG_* or -c?)" % eff)
    bad = worktree_overrides(repo, hooks_dir)
    if bad:
        raise InstallError("linked worktree(s) override core.hooksPath via "
                           "extensions.worktreeConfig, so the shims would not run there:\n  "
                           + "\n  ".join("%s -> %r" % b for b in bad)
                           + "\nRemove those per-worktree values (git config --worktree "
                             "--unset core.hooksPath) and re-run.")
    if not changed:
        log("up to date: %s" % hooks_dir)
    return hooks_dir


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--repo", default=os.getcwd(), help="any checkout/worktree of the clone")
    ap.add_argument("--check", action="store_true", help="verify only; write nothing")
    args = ap.parse_args(argv)
    repo = os.path.abspath(args.repo)
    try:
        if args.check:
            hooks_dir, problems = check(repo)
            for p in problems:
                print("DRIFT: " + p)
            if problems:
                print("run: python tools/install_hooks.py --repo \"%s\"" % repo)
                return 1
            print("ok: %s" % hooks_dir)
            return 0
        install(repo, print)
        return 0
    except InstallError as e:
        print("install_hooks: ERROR: %s" % e, file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
